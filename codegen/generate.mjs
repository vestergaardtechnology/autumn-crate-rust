// The approval rule filter DSL is a MongoDB-style query language that the JS
// SDK expands into ~5,000 generated types. In Rust it is far more usable as a
// JSON value built with `serde_json::json!`.
const FILTER_SCHEMAS = new Set(["ApprovalRuleFilterUnion", "ApprovalRuleFilterOutputUnion"]);
const FILTER_TYPE = "ApprovalRuleFilter";

// ---------------------------------------------------------------------------
// Collapse unions of structurally identical options
// ---------------------------------------------------------------------------
//
// Speakeasy emits one schema per documented status code, so e.g. the 200 and
// 202 bodies of `check` become `CheckResponseBody1 | CheckResponseBody2` even
// though both have exactly the same shape. In TypeScript that union is
// invisible; in Rust it would force a `match` on every call. Unions whose
// options are deeply identical are replaced by their first option.

const sigMemo = new Map();
function schemaSig(name) {
  if (sigMemo.has(name)) return sigMemo.get(name);
  sigMemo.set(name, "rec"); // cycle guard
  const s = ir.schemas[name];
  const node = s.inbound ?? s.outbound;
  const sig = (s.inbound ? "in:" : "out:") + nodeSig(node, s.inbound ? "in" : "out");
  sigMemo.set(name, sig);
  return sig;
}
function nodeSig(n, dir) {
  switch (n.kind) {
    case "ref":
      return FILTER_SCHEMAS.has(n.name) ? "filter" : schemaSig(n.name);
    case "enum": {
      const e = ir.enums[n.name];
      return `enum(${e.open}:${e.values.map((v) => v.value).sort().join(",")})`;
    }
    case "object": {
      const fields = n.fields
        .map((f) => {
          const wire = dir === "out" ? (f.key in n.remap ? n.remap[f.key] : f.key) : f.key;
          return wire === null ? null : `${wire}=${nodeSig(f.type, dir)}`;
        })
        .filter(Boolean)
        .sort();
      return `{${fields.join(";")}${n.catchall ? ";*" : ""}}`;
    }
    case "union": {
      // Normalized so the signature doesn't depend on whether nested unions
      // were already collapsed.
      const sigs = n.options.map((o) => nodeSig(o, dir));
      return sigs.every((s) => s === sigs[0]) ? sigs[0] : `union(${sigs.join("|")})`;
    }
    case "taggedUnion":
      return `tagged(${n.prop}:${n.options.map((o) => o.tag + "=" + nodeSig(o.type, dir)).join("|")})`;
    case "literal":
      return `lit(${JSON.stringify(n.value)}${n.lenient ? "?" : ""})`;
    case "default":
      return `default(${nodeSig(n.inner, dir)})`;
    case "optional":
    case "nullable":
    case "array":
      return `${n.kind}(${nodeSig(n.inner, dir)})`;
    case "record":
      return `record(${nodeSig(n.value, dir)})`;
    case "inlineEnum":
      return `enum(${n.values.join(",")})`;
    default:
      return n.kind;
  }
}
function collapseUnions(n) {
  if (!n || typeof n !== "object") return n;
  if (n.kind === "union") {
    n.options = n.options.map(collapseUnions);
    if (n.options.length > 1 && n.options.every((o) => o.kind === "ref")) {
      const first = nodeSig(n.options[0]);
      if (n.options.every((o) => nodeSig(o) === first)) return n.options[0];
    }
    return n;
  }
  for (const k of ["inner", "value"]) if (n[k] && typeof n[k] === "object") n[k] = collapseUnions(n[k]);
  if (n.kind === "taggedUnion") for (const o of n.options) o.type = collapseUnions(o.type);
  if (n.fields) for (const f of n.fields) f.type = collapseUnions(f.type);
  return n;
}
let collapsed = 0;
for (const s of Object.values(ir.schemas)) {
  for (const dir of ["inbound", "outbound"]) {
    if (!s[dir]) continue;
    const before = s[dir].kind;
    s[dir] = collapseUnions(s[dir]);
    if (before === "union" && s[dir].kind === "ref") collapsed++;
  }
}
for (const cls of Object.values(ir.classes)) {
  for (const m of cls.methods) {
    if (m.request) m.request = collapseUnions(m.request);
    for (const r of m.responses) r.type = collapseUnions(r.type);
  }
}

