const defs = new Map(); // rust name -> def
const literals = new Map(); // json value -> rust name
const usedNames = new Set([...reach.keys()].map(rustTypeName));
for (const e of Object.keys(ir.enums)) usedNames.add(e);
usedNames.add(FILTER_TYPE);

function literalType(value) {
  const key = JSON.stringify(value);
  if (literals.has(key)) return literals.get(key);
  let name = value === "" ? "Empty" : pascal(String(value)) || "Value";
  const taken = new Set(literals.values());
  let n = name;
  for (let i = 2; taken.has(n); i++) n = name + i;
  literals.set(key, n);
  return n;
}

function freshName(base) {
  let n = base;
  for (let i = 2; usedNames.has(n); i++) n = base + i;
  usedNames.add(n);
  return n;
}

// Type AST: {t:"prim", rust} | {t:"value"} | {t:"named", name} | {t:"vec", inner}
//           | {t:"map", inner} | {t:"opt", inner} | {t:"lit", name}
function tyOf(node, dir, ctx) {
  switch (node.kind) {
    case "string":
      return { t: "prim", rust: "String", prim: "string" };
    case "number":
      return { t: "prim", rust: "f64", prim: "number" };
    case "int":
      return { t: "prim", rust: "i64", prim: "int" };
    case "boolean":
      return { t: "prim", rust: "bool", prim: "boolean" };
    case "any":
      return { t: "value" };
    case "null":
      return { t: "null" };
    case "literal":
      return { t: "lit", name: literalType(node.value), value: node.value };
    case "ref":
      if (FILTER_SCHEMAS.has(node.name)) return { t: "named", name: FILTER_TYPE };
      return { t: "named", name: rustTypeName(node.name) };
    case "enum":
      return { t: "named", name: node.name };
    case "array":
      return { t: "vec", inner: tyOf(node.inner, dir, ctx) };
    case "record":
      return { t: "map", inner: tyOf(node.value, dir, ctx) };
    case "optional":
    case "nullable":
    case "default":
      return { t: "opt", inner: tyOf(node.inner, dir, ctx) };
    case "union":
    case "taggedUnion": {
      const name = freshName(ctx + "Union");
      defineUnion(name, node, dir, null);
      return { t: "named", name };
    }
    case "object": {
      const name = freshName(ctx);
      defineStruct(name, node, dir, null);
      return { t: "named", name };
    }
    case "inlineEnum": {
      const name = freshName(ctx);
      defs.set(name, {
        kind: "enum",
        name,
        open: dir === "in",
        values: node.values.map((v) => ({ key: pascal(v), value: v })),
        doc: null,
      });
      return { t: "named", name };
    }
    default:
      throw new Error("unhandled node kind " + node.kind);
  }
}

function unwrapField(node) {
  // Returns { flags, inner } describing optional/nullable/default wrappers.
  const flags = { optional: false, nullable: false, lenient: false, defaultValue: undefined };
  let n = node;
  for (;;) {
    if (n.kind === "optional") {
      flags.optional = true;
      flags.lenient ||= !!n.lenient;
    } else if (n.kind === "nullable") flags.nullable = true;
    else if (n.kind === "default") {
      flags.optional = true;
      flags.defaultValue = n.value;
    } else break;
    n = n.inner;
  }
  if (n.kind === "literal" && n.lenient) flags.lenient = true;
  return { flags, inner: n };
}

function defineStruct(name, node, dir, schemaName) {
  const docs = ir.typeDocs[schemaName ?? name] ?? { doc: null, fields: {} };
  const fields = [];
  const taken = new Set();
  for (const f of node.fields) {
    let wire, camel;
    if (dir === "out") {
      camel = f.key;
      wire = f.key in node.remap ? node.remap[f.key] : f.key;
      if (wire === null) continue;
    } else {
      wire = f.key;
      camel = node.remap[f.key] ?? f.key;
    }
    let base = snake(wire);
    let rname = base;
    for (let i = 2; taken.has(rname); i++) rname = base + "_" + i;
    taken.add(rname);
    const { flags, inner } = unwrapField(f.type);
    const ty = tyOf(inner, dir, name + pascal(camel));
    fields.push({ wire, rname, ty, flags, doc: docs.fields[camel] ?? null });
  }
  defs.set(name, { kind: "struct", name, dir, fields, catchall: !!node.catchall, doc: docs.doc, schemaName });
}

function variantName(ty, unionName) {
  switch (ty.t) {
    case "prim":
      return { String: "String", f64: "Number", i64: "Integer", bool: "Boolean" }[ty.rust];
    case "value":
      return "Value";
    case "null":
      return "Null";
    case "lit":
      return ty.name;
    case "vec":
      return variantName(ty.inner, unionName) + "Array";
    case "map":
      return variantName(ty.inner, unionName) + "Map";
    case "opt":
      return variantName(ty.inner, unionName);
    case "named": {
      // Strip the union's own name as a prefix when it leaves something sensible.
      let n = ty.name;
      const base = unionName.replace(/Union$/, "");
      for (const prefix of [unionName, base]) {
        if (n.startsWith(prefix) && n.length > prefix.length && /^[A-Z]/.test(n.slice(prefix.length))) {
          n = n.slice(prefix.length);
          break;
        }
      }
      return n;
    }
  }
  return "Variant";
}

function defineUnion(name, node, dir, schemaName) {
  const docs = ir.typeDocs[schemaName ?? name] ?? { doc: null };
  const options = node.kind === "taggedUnion" ? node.options.map((o) => o.type) : node.options;
  const variants = [];
  const taken = new Set();
  options.forEach((opt, i) => {
    const ty = tyOf(opt, dir, name + "Variant" + (i + 1));
    let vn = variantName(ty, name);
    if (!/^[A-Z]/.test(vn)) vn = "V" + vn;
    let n = vn;
    for (let k = 2; taken.has(n); k++) n = vn + k;
    taken.add(n);
    variants.push({ name: n, ty });
  });
  defs.set(name, {
    kind: "union",
    name,
    dir,
    variants,
    tagged: node.kind === "taggedUnion" ? node.prop : null,
    doc: docs.doc,
  });
}

