const moduleOf = new Map();
for (const [name, owners] of reach) {
  moduleOf.set(rustTypeName(name), owners.size === 1 ? [...owners][0] : "shared");
}
// Synthesized and enum types follow whoever references them first.
function assignModules() {
  let changed = true;
  while (changed) {
    changed = false;
    for (const def of defs.values()) {
      const mod = moduleOf.get(def.name);
      if (!mod) continue;
      const refs = [];
      collectNamed(def, refs);
      for (const r of refs) {
        if (!defs.has(r) || r === FILTER_TYPE) continue;
        const cur = moduleOf.get(r);
        if (cur === undefined) {
          moduleOf.set(r, mod);
          changed = true;
        } else if (cur !== mod && cur !== "shared" && !reach.has(r)) {
          moduleOf.set(r, "shared");
          changed = true;
        }
      }
    }
  }
}
function collectNamed(def, out) {
  const walk = (ty) => {
    if (!ty) return;
    if (ty.t === "named") out.push(ty.name);
    if (ty.inner) walk(ty.inner);
  };
  if (def.kind === "struct") def.fields.forEach((f) => walk(f.ty));
  else if (def.kind === "union") def.variants.forEach((v) => walk(v.ty));
  else if (def.kind === "alias") walk(def.ty);
}
assignModules();
for (const def of defs.values()) if (!moduleOf.has(def.name)) moduleOf.set(def.name, "shared");

// ---------------------------------------------------------------------------
// Recursion: box by-value cycles
// ---------------------------------------------------------------------------

function byValueRefs(ty, out) {
  if (!ty) return;
  if (ty.t === "named") out.push(ty.name);
  else if (ty.t === "opt") byValueRefs(ty.inner, out);
}
const graph = new Map();
for (const def of defs.values()) {
  const out = [];
  if (def.kind === "struct") def.fields.forEach((f) => byValueRefs(f.ty, out));
  else if (def.kind === "union") def.variants.forEach((v) => byValueRefs(v.ty, out));
  else if (def.kind === "alias") byValueRefs(def.ty, out);
  graph.set(def.name, out.filter((n) => defs.has(n)));
}
const sccOf = new Map();
{
  let index = 0;
  const stack = [];
  const idx = new Map();
  const low = new Map();
  const on = new Set();
  let sccId = 0;
  const strong = (v) => {
    idx.set(v, index);
    low.set(v, index);
    index++;
    stack.push(v);
    on.add(v);
    for (const w of graph.get(v) ?? []) {
      if (!idx.has(w)) {
        strong(w);
        low.set(v, Math.min(low.get(v), low.get(w)));
      } else if (on.has(w)) low.set(v, Math.min(low.get(v), idx.get(w)));
    }
    if (low.get(v) === idx.get(v)) {
      let w;
      do {
        w = stack.pop();
        on.delete(w);
        sccOf.set(w, sccId);
      } while (w !== v);
      sccId++;
    }
  };
  for (const v of graph.keys()) if (!idx.has(v)) strong(v);
}
const needsBox = (owner, target) =>
  defs.has(target) && sccOf.get(owner) === sccOf.get(target) && (graph.get(owner) ?? []).includes(target);

