const KEYWORDS = new Set(
  "as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try gen".split(
    " ",
  ),
);
const NON_RAW = new Set(["self", "Self", "super", "crate"]);

function snake(name) {
  let s = name
    .replace(/\$/g, "dollar_")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9_]+/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toLowerCase();
  if (!s) s = "field";
  if (/^[0-9]/.test(s)) s = "n" + s;
  return s;
}

function ident(name) {
  if (NON_RAW.has(name)) return name + "_";
  if (KEYWORDS.has(name)) return "r#" + name;
  return name;
}

function pascal(s) {
  const p = String(s)
    .replace(/\$/g, " dollar ")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
  return /^[0-9]/.test(p) ? "N" + p : p;
}

