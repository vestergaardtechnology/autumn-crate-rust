function eachRef(node, fn) {
  if (!node || typeof node !== "object") return;
  if (node.kind === "ref") return fn(node.name);
  for (const k of ["inner", "value", "key"]) if (node[k] && typeof node[k] === "object") eachRef(node[k], fn);
  if (node.options) for (const o of node.options) eachRef(o.type ?? o, fn);
  if (node.fields) for (const f of node.fields) eachRef(f.type, fn);
}

function schemaOf(name) {
  const s = ir.schemas[name];
  if (!s) throw new Error("missing schema " + name);
  if (s.inbound && s.outbound) throw new Error("schema with both directions: " + name);
  return s.inbound ? { dir: "in", node: s.inbound } : { dir: "out", node: s.outbound };
}

const reach = new Map(); // name -> Set(resource)
function visit(name, owner) {
  if (FILTER_SCHEMAS.has(name)) return;
  let set = reach.get(name);
  if (set && set.has(owner)) return;
  if (!set) reach.set(name, (set = new Set()));
  set.add(owner);
  eachRef(schemaOf(name).node, (n) => visit(n, owner));
}
const resourceOf = (className) => (className === "Autumn" ? "core" : snake(className));
for (const op of ops) {
  const owner = resourceOf(op.className);
  if (op.request && op.sendsBody) eachRef(op.request, (n) => visit(n, owner));
  for (const r of op.responses) eachRef(r.type, (n) => visit(n, owner));
}

