// Fixture tests: synthetic wire payloads for every operation
// ---------------------------------------------------------------------------
//
// For each operation we synthesize request and response JSON straight from the
// schemas (all fields / required fields only / last union branch) and check
// that the generated types parse them, and that requests round-trip exactly.

function sample(node, dir, mode, depth = 0) {
  switch (node.kind) {
    case "string":
      return "str";
    case "number":
      return 1.5;
    case "int":
      return 2;
    case "boolean":
      return true;
    case "any":
      return { any: "value" };
    case "null":
      return null;
    case "literal":
      return node.value;
    case "enum":
      return ir.enums[node.name].values[mode === "alt" ? ir.enums[node.name].values.length - 1 : 0].value;
    case "inlineEnum":
      return node.values[0];
    case "array":
      return depth > 8 ? [] : [sample(node.inner, dir, mode, depth + 1)];
    case "record":
      return depth > 8 ? {} : { key: sample(node.value, dir, mode, depth + 1) };
    case "optional":
    case "nullable":
    case "default":
      return sample(node.inner, dir, mode, depth);
    case "union": {
      const o = mode === "alt" ? node.options[node.options.length - 1] : node.options[0];
      return sample(o, dir, mode, depth);
    }
    case "taggedUnion":
      return sample((mode === "alt" ? node.options[node.options.length - 1] : node.options[0]).type, dir, mode, depth);
    case "ref": {
      if (FILTER_SCHEMAS.has(node.name)) return { plan_id: { $in: ["pro"] } };
      const s = schemaOf(node.name);
      return sample(s.node, s.dir, mode, depth + 1);
    }
    case "object": {
      const out = {};
      for (const f of node.fields) {
        const wire = dir === "out" ? (f.key in node.remap ? node.remap[f.key] : f.key) : f.key;
        if (wire === null) continue;
        const { flags } = unwrapField(f.type);
        const optional = flags.optional || flags.nullable;
        if (optional && (mode === "min" || depth > 8)) {
          // Required-but-nullable fields are always present on the wire.
          if (!flags.optional) out[wire] = null;
          continue;
        }
        out[wire] = sample(f.type, dir, mode, depth + 1);
      }
      return out;
    }
  }
  throw new Error("sample " + node.kind);
}

