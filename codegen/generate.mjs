function cleanDoc(text) {
  if (!text) return [];
  const out = [];
  let fence = false;
  for (let line of text.replace(/\r/g, "").split("\n")) {
    if (/^\s*```/.test(line)) {
      const lang = line.trim().slice(3).trim();
      if (!fence) line = "```" + (lang && lang !== "rust" ? lang : "text");
      else line = "```";
      fence = !fence;
      out.push(line);
      continue;
    }
    // Indented blocks would be compiled as doctests; flatten them.
    out.push(fence ? line : line.replace(/^\s+/, ""));
  }
  if (fence) out.push("```");
  while (out.length && !out[out.length - 1].trim()) out.pop();
  while (out.length && !out[0].trim()) out.shift();
  return out;
}

function docLines(text, indent = "") {
  return cleanDoc(text).map((l) => `${indent}///${l ? " " + l : ""}`);
}

function methodDoc(text) {
  // JSDoc from the JS SDK: drop TypeScript examples and @param lines (fields
  // are documented on the request struct), keep the description/returns.
  if (!text) return [];
  const lines = text.replace(/\r/g, "").split("\n");
  const out = [];
  let skipping = false;
  let fence = false;
  for (const line of lines) {
    if (/^\s*```/.test(line)) {
      fence = !fence;
      if (skipping) continue;
    }
    if (fence && skipping) continue;
    if (/^@example/.test(line)) {
      skipping = true;
      continue;
    }
    if (/^@param/.test(line)) {
      skipping = true;
      continue;
    }
    if (/^@returns?\s/.test(line)) {
      skipping = false;
      out.push("", "**Returns:** " + line.replace(/^@returns?\s+/, ""));
      continue;
    }
    if (/^@/.test(line)) {
      skipping = true;
      continue;
    }
    if (skipping && line.trim() === "") continue;
    if (skipping && !fence) skipping = false;
    out.push(line);
  }
  return cleanDoc(out.join("\n").replace(/\n{3,}/g, "\n\n"));
}

