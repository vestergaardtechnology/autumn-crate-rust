function opConst(op) {
  return "OP_" + snake(op.operationId).toUpperCase();
}

function requestTy(op) {
  if (!op.request || !op.sendsBody) return null;
  let node = op.request;
  if (node.kind === "optional") node = node.inner;
  return render(tyOf(node, "out", pascal(op.operationId) + "Request"), null);
}

function responseTy(op) {
  const tys = [...new Set(op.responses.map((r) => render(tyOf(r.type, "in", pascal(op.operationId) + "Response"), null)))];
  if (tys.length !== 1) throw new Error("multiple response types for " + op.operationId);
  return tys[0];
}

function renderOperation(op, receiver) {
  const reqTy = requestTy(op);
  const resTy = responseTy(op);
  const lines = [];
  const doc = methodDoc(op.doc);
  lines.push(...doc.map((l) => `    ///${l ? " " + l : ""}`));
  if (doc.length) lines.push("    ///");
  lines.push(`    /// \`POST /${op.path.replace(/^\//, "")}\` (operation \`${op.operationId}\`)`);
  const name = methodName(op.name);
  if (reqTy) {
    lines.push(`    pub async fn ${name}(&self, request: ${reqTy}) -> Result<${resTy}> {`);
    lines.push(`        ${receiver}.execute(&${opConst(op)}, Some(&request)).await`);
  } else {
    lines.push(`    pub async fn ${name}(&self) -> Result<${resTy}> {`);
    lines.push(`        ${receiver}.execute::<(), _>(&${opConst(op)}, None).await`);
  }
  lines.push(`    }`);
  return lines;
}

