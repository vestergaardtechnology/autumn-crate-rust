    "    use serde_json::Value::*;",
    "    match (a, b) {",
    "        (Object(x), Object(y)) => x.keys().chain(y.keys()).find_map(|k| match (x.get(k), y.get(k)) {",
    "            (Some(l), Some(r)) => diff(l, r, format!(\"{path}.{k}\")),",
    "            (l, r) => Some(format!(\"{path}.{k}: {l:?} != {r:?}\")),",
    "        }),",
    "        (Array(x), Array(y)) if x.len() == y.len() => x.iter().zip(y).enumerate().find_map(|(i, (l, r))| diff(l, r, format!(\"{path}[{i}]\"))),",
    "        _ if a == b => None,",
