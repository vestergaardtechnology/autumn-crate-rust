function render(ty, owner, byValue = true) {
  switch (ty.t) {
    case "prim":
      return ty.rust;
    case "value":
      return "serde_json::Value";
    case "null":
      return "()";
    case "lit":
      return `literals::${ty.name}`;
    case "vec":
      return `Vec<${render(ty.inner, owner, false)}>`;
    case "map":
      return `HashMap<String, ${render(ty.inner, owner, false)}>`;
    case "opt":
      return `Option<${render(ty.inner, owner, byValue)}>`;
    case "named":
      return byValue && owner && needsBox(owner, ty.name) ? `Box<${ty.name}>` : ty.name;
  }
  throw new Error("render " + ty.t);
}

const defaultMemo = new Map();
function isDefault(ty) {
  switch (ty.t) {
    case "prim":
    case "value":
    case "vec":
    case "map":
    case "opt":
    case "lit":
    case "null":
      return true;
    case "named": {
      if (ty.name === FILTER_TYPE) return true;
      const def = defs.get(ty.name);
      if (!def) return false;
      if (defaultMemo.has(ty.name)) return defaultMemo.get(ty.name);
      defaultMemo.set(ty.name, true); // optimistic for cycles
      let r;
      if (def.kind === "struct") r = def.fields.every((f) => fieldIsDefault(f));
      else if (def.kind === "alias") r = isDefault(def.ty);
      else r = false;
      defaultMemo.set(ty.name, r);
      return r;
    }
  }
  return false;
}
const fieldIsDefault = (f) => f.flags.optional || f.flags.nullable || isDefault(f.ty);

function requiredCount(ty) {
  if (ty.t !== "named") return 0;
  const def = defs.get(ty.name);
  if (!def || def.kind !== "struct") return 0;
  return def.fields.filter((f) => !f.flags.optional && !f.flags.nullable).length;
}

function variantRank(ty) {
  // Lower ranks are tried first when deserializing an untagged union.
  switch (ty.t) {
    case "null":
      return [0];
    case "lit":
      return [1];
    case "prim":
      return [{ bool: 2, i64: 3, f64: 4, String: 7 }[ty.rust]];
    case "vec":
      return [8];
    case "opt":
      return variantRank(ty.inner);
    case "map":
      return [20];
    case "value":
      return [30];
    case "named": {
      const def = defs.get(ty.name);
      if (!def) return [25];
      if (def.kind === "enum") return [def.open ? 6 : 5];
      if (def.kind === "struct") {
        const nf = def.fields.length;
        return [10, -requiredCount(ty), -nf];
      }
      if (def.kind === "alias") return variantRank(def.ty);
      return [15];
    }
  }
  return [99];
}
const cmpRank = (a, b) => {
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    const d = (a[i] ?? 0) - (b[i] ?? 0);
    if (d) return d;
  }
  return 0;
};

// Structs that are (directly) a variant of an untagged union.
const unionVariantStructs = new Set();
for (const d of defs.values()) {
  if (d.kind !== "union") continue;
  for (const v of d.variants) {
    let t = v.ty;
    while (t.t === "opt" || t.t === "vec") t = t.inner;
    if (t.t === "named") unionVariantStructs.add(t.name);
  }
}

function renderStruct(def) {
  const lines = [];
  const derives = ["Debug", "Clone", "PartialEq", "Serialize", "Deserialize"];
  const canDefault = isDefault({ t: "named", name: def.name });
  if (canDefault) derives.push("Default");
  lines.push(...docLines(def.doc));
  lines.push(`#[derive(${derives.join(", ")})]`);
  lines.push(`pub struct ${def.name} {`);
  for (const f of def.fields) {
    const attrs = [];
    if (f.wire !== f.rname.replace(/^r#/, "")) attrs.push(`rename = "${f.wire.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`);
    const { optional, nullable, lenient } = f.flags;
    let ty;
    const inner = render(f.ty, def.name);
    if (def.dir === "out") {
      if (optional && nullable) {
        ty = `Option<Option<${inner}>>`;
        attrs.push(`default`, `skip_serializing_if = "Option::is_none"`, `deserialize_with = "crate::util::double_option"`);
      } else if (optional) {
        ty = `Option<${inner}>`;
        attrs.push(`default`, `skip_serializing_if = "Option::is_none"`);
      } else if (nullable) {
        ty = `Option<${inner}>`;
        attrs.push(`default`);
      } else {
        ty = inner;
        if (f.ty.t === "lit") attrs.push("default");
      }
    } else {
      if (optional) {
        ty = `Option<${inner}>`;
        attrs.push(`default`, `skip_serializing_if = "Option::is_none"`);
      } else if (nullable) {
        ty = `Option<${inner}>`;
        attrs.push(`default`);
      } else {
        ty = inner;
        if (f.ty.t === "prim" || (f.ty.t === "lit" && lenient)) {
          // Missing fields default to zero like the JS SDK, except in union
          // variants, where a missing field must reject the variant so the
          // next one is tried (the JS SDK's smartUnion picks the candidate
          // with the fewest defaulted fields).
          if (!unionVariantStructs.has(def.name)) attrs.push(`default`);
          attrs.push(`deserialize_with = "crate::util::lenient"`);
        }
      }
    }
    const doc = [...cleanDoc(f.doc)];
    if (f.flags.defaultValue !== undefined) {
      if (doc.length) doc.push("");
      doc.push(`Defaults to \`${JSON.stringify(f.flags.defaultValue)}\` when omitted.`);
    }
    lines.push(...doc.map((l) => `    ///${l ? " " + l : ""}`));
    if (attrs.length) lines.push(`    #[serde(${attrs.join(", ")})]`);
    lines.push(`    pub ${ident(f.rname)}: ${ty},`);
    f.renderedTy = ty;
    f.innerTy = inner;
  }
  if (def.catchall) {
    lines.push(`    /// Any additional properties not covered by the fields above.`);
    lines.push(`    #[serde(flatten)]`);
    lines.push(`    pub additional_properties: HashMap<String, serde_json::Value>,`);
  }
  lines.push("}");
  if (def.dir === "out") lines.push("", ...renderBuilder(def));
  return lines;
}

function renderBuilder(def) {
  const required = def.fields.filter((f) => !f.flags.optional && f.ty.t !== "lit");
  // Nullable required fields take the value itself; set the field to `None` to send null.
  const params = required.map((f) => `${ident(f.rname)}: impl Into<${f.flags.nullable ? f.innerTy : f.renderedTy}>`);
  const out = [`impl ${def.name} {`];
  out.push(`    /// Creates a new [\`${def.name}\`] from its required fields.`);
  out.push(`    pub fn new(${params.join(", ")}) -> Self {`);
  out.push(`        Self {`);
  for (const f of def.fields) {
    const id = ident(f.rname);
    if (f.flags.optional) out.push(`            ${id}: None,`);
    else if (f.ty.t === "lit") out.push(`            ${id}: Default::default(),`);
    else if (f.flags.nullable) out.push(`            ${id}: Some(${id}.into()),`);
    else out.push(`            ${id}: ${id}.into(),`);
  }
  if (def.catchall) out.push(`            additional_properties: HashMap::new(),`);
  out.push(`        }`, `    }`);
  const methodNames = new Set(["new"]);
  for (const f of def.fields.filter((f) => f.flags.optional)) {
    let m = f.rname;
    if (methodNames.has(m)) m = m + "_";
    methodNames.add(m);
    const id = ident(f.rname);
    const val = f.flags.nullable ? "Some(Some(value.into()))" : "Some(value.into())";
    out.push("");
    out.push(`    /// Sets [\`${f.rname}\`](Self::${id}).`);
    out.push(`    pub fn ${ident(m)}(mut self, value: impl Into<${f.innerTy}>) -> Self {`);
    out.push(`        self.${id} = ${val};`);
    out.push(`        self`);
    out.push(`    }`);
  }
  if (def.catchall) {
    out.push("");
    out.push(`    /// Adds an additional property.`);
    out.push(`    pub fn additional_property(mut self, key: impl Into<String>, value: impl Into<serde_json::Value>) -> Self {`);
    out.push(`        self.additional_properties.insert(key.into(), value.into());`);
    out.push(`        self`);
    out.push(`    }`);
  }
  out.push("}");
  return out;
}

function renderUnion(def) {
  const lines = [...docLines(def.doc)];
  if (def.tagged) {
    if (lines.length) lines.push("///");
    lines.push(`/// Discriminated by the \`${def.tagged}\` property.`);
  }
  lines.push(`#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]`);
  lines.push(`#[serde(untagged)]`);
  lines.push(`pub enum ${def.name} {`);
  const ordered = [...def.variants].sort((a, b) => cmpRank(variantRank(a.ty), variantRank(b.ty)));
  for (const v of ordered) {
    if (v.ty.t === "null") lines.push(`    ${v.name},`);
    else lines.push(`    ${v.name}(${render(v.ty, def.name)}),`);
  }
  if (def.tagged) {
    lines.push(`    /// A variant this version of the SDK does not know about.`);
    lines.push(`    Unknown(serde_json::Value),`);
  }
  lines.push("}");
  // From impls when every variant has a distinct type.
  const tys = def.variants.filter((v) => v.ty.t !== "null").map((v) => render(v.ty, def.name));
  if (new Set(tys).size === tys.length) {
    for (const v of def.variants) {
      if (v.ty.t === "null") continue;
      const t = render(v.ty, def.name);
      const boxed = t.startsWith("Box<");
      lines.push("", `impl From<${boxed ? t.slice(4, -1) : t}> for ${def.name} {`);
      lines.push(`    fn from(value: ${boxed ? t.slice(4, -1) : t}) -> Self {`);
      lines.push(`        Self::${v.name}(${boxed ? "Box::new(value)" : "value"})`);
      lines.push(`    }`, `}`);
      if (t === "String") {
        lines.push("", `impl From<&str> for ${def.name} {`);
        lines.push(`    fn from(value: &str) -> Self {`);
        lines.push(`        Self::${v.name}(value.to_owned())`);
        lines.push(`    }`, `}`);
      }
    }
  }
  return lines;
}

function enumVariant(key, value, taken) {
  let v = pascal(key) || pascal(value) || "Value";
  if (v === "Unknown" || v === "Self") v += "Value";
  let n = v;
  for (let i = 2; taken.has(n); i++) n = v + i;
  taken.add(n);
  return n;
}

function renderEnum(def) {
  const lines = [`${def.open ? "open_enum" : "closed_enum"}! {`];
  lines.push(...docLines(def.doc, "    "));
  lines.push(`    pub enum ${def.name} {`);
  const taken = new Set();
  for (const { key, value } of def.values) {
    const d = def.valueDocs?.[key];
    if (d) lines.push(...docLines(d, "        "));
    lines.push(`        ${enumVariant(key, value, taken)} = ${JSON.stringify(String(value))},`);
  }
  lines.push(`    }`, `}`);
  return lines;
}

function renderAlias(def) {
  return [...docLines(def.doc), `pub type ${def.name} = ${render(def.ty, def.name)};`];
}

